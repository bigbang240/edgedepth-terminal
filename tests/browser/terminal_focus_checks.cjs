// UI regression on the production WASM and recorded HL fixture. Invoked by
// CHECK_CONTROLS=1 tools/record_hl_rails.cjs (use TF=14400 ZOOMY=6 for BTC).
const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async (page, out) => {
  const rects = () => page.evaluate(() => window.__EDGEDEPTH_UI_RECTS__ || {});
  const click = async id => {
    await page.waitForFunction(id => window.__EDGEDEPTH_UI_RECTS__?.[id], id);
    const [x0, y0, x1, y1] = (await rects())[id];
    await page.mouse.move((x0+x1)/2, (y0+y1)/2);
    await page.waitForTimeout(120);
    await page.mouse.click((x0+x1)/2, (y0+y1)/2);
    await page.waitForTimeout(350);
  };
  const settings = () => page.evaluate(() => {
    Module._workspace_flush();
    return JSON.parse(sessionStorage.getItem('edgedepth.workspace.tab.v1')).widgets.find(w => w.type === 'chart').settings;
  });
  const levels = async () => Object.keys(await rects()).filter(k => k.startsWith('hl.level.')).length;
  const shot = async name => { await page.mouse.move(3, 800); await page.waitForTimeout(250); await page.screenshot({path:path.join(out, name+'.png')}); };
  let s = await settings();
  assert.equal(s.chart_layer_defaults, 3);
  for (const key of ['liq_markers', 'candle_refill', 'activity_enabled', 'hl_rails_profile', 'model_rails_profile', 'touch_odds_enabled', 'rail_value_labels']) assert.equal(s[key], false, key);
  assert.equal(s.hl_major_levels, true);
  const major = await levels();
  assert.ok(major > 0 && major <= 12, `major rail count ${major}`);
  await shot('01-major-levels');
  await click('chart.liquidations');
  let r = await rects();
  assert.ok(r['layer.Hyperliquid positions.settings'] && r['layer.Liquidation map'] && r['layer.Reported liquidations']);
  assert.ok(!r['overlay.hl.profile'] && !r['layer.Order book depth']);
  await shot('02-liquidations-menu');
  // Switching reported liquidations on brings the candle callouts with it.
  await click('layer.Reported liquidations');
  s = await settings();
  assert.equal(s.liq_observed_enabled, true, 'reported liquidations on');
  assert.equal(s.liq_markers, true, 'callouts follow the source switch');
  await click('layer.Reported liquidations');
  assert.equal((await settings()).liq_observed_enabled, false, 'reported liquidations off again');
  await click('layer.Hyperliquid positions.settings');
  assert.equal((await settings()).liq_census_enabled, true, 'disclosure does not toggle source');
  r = await rects();
  assert.ok(r['overlay.hl.profile'] && !r['layer.Liquidation map']);
  await shot('03-source-settings');
  await click('overlay.hl.profile');
  assert.equal((await settings()).hl_rails_profile, true);
  await click('overlay.back');
  await click('hl_detail.More detail');
  const more = await levels();
  assert.ok(more > major, `more detail ${more} > major ${major}`);
  await page.keyboard.press('Escape');
  await shot('04-more-detail');
  await click('chart.liquidations');
  const mapBefore = (await settings()).liq_dense_field;
  await click('layer.Hyperliquid positions');
  assert.equal((await settings()).liq_census_enabled, false);
  assert.equal((await settings()).liq_dense_field, mapBefore);
  await click('layer.Hyperliquid positions');
  await page.keyboard.press('Escape');
  await click('chart.layers');
  r = await rects();
  assert.ok(r['overlay.price'] && r['layer.Order book depth']);
  assert.ok(!r['layer.Hyperliquid positions']);
  await shot('05-layers-menu');
  await click('overlay.price');
  r = await rects();
  assert.ok(r['layer.Daily VWAP (UTC)'] && !r['layer.Order book depth']);
  await page.keyboard.press('Escape');
  await settings();
  await page.reload();
  await page.waitForFunction(() => typeof Module?._workspace_flush === 'function', null, {timeout:90000});
  await page.waitForTimeout(4500);
  s = await settings();
  assert.equal(s.hl_major_levels, false, 'density survives reload');
  assert.equal(s.hl_rails_profile, true, 'opt-in profile survives reload');
  assert.equal(s.liq_census_enabled, true, 'source choice survives reload');
  await click('chart.liquidations');
  await click('hl_detail.Major levels');
  await click('layer.Hyperliquid positions.settings');
  await click('overlay.hl.profile');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:760, height:900});
  await page.waitForTimeout(1000);
  await click('chart.liquidations');
  r = await rects();
  const last = r['hl_detail.More detail'];
  assert.ok(last && last[2] <= 760 && last[3] <= 900, 'narrow menu fits');
  await shot('06-narrow-liquidations');
  await page.keyboard.press('Escape');
  await click('chart.layers');
  r = await rects();
  assert.ok(r['layer.Order book depth'][2] <= 760, 'narrow Layers menu fits');
  await shot('07-narrow-layers');
  await page.keyboard.press('Escape');
  console.log(`PASS terminal focus: ${major} major rails / ${more} detail rails; menu navigation, independent switches, migration, persistence, narrow layout`);
};
